# build_dashboard.py
# Packs the SQL query results in results/ into dashboard/data.js for the dashboard page.

import json
import pandas as pd

def rows(name):
    return pd.read_csv(f"results/{name}.csv").to_dict(orient="records")

data = {
    "departments": rows("department_on_time"),
    "monthly_on_time": rows("monthly_on_time"),
    "monthly_requests": rows("monthly_requests"),
    "dot_by_area": rows("dot_by_area"),
    "dot_by_district": rows("dot_by_district"),
    "contact_source": rows("contact_source"),
    "top_requests": rows("top_requests"),
}
d = pd.read_csv("results/department_on_time.csv")
data["totals"] = {
    "requests": int(pd.read_csv("results/monthly_requests.csv").requests.sum()),
    "closed_with_deadline": int(d.closed_requests.sum()),
    "late": int(d.late_requests.sum()),
    "dot_late": int(d.loc[d.department == "DOT", "late_requests"].iloc[0]),
}
with open("dashboard/data.js", "w") as f:
    f.write("// Generated by build_dashboard.py from results/*.csv. Do not edit by hand.\n")
    f.write("window.MC311 = " + json.dumps(data, indent=1) + ";\n")
print("dashboard/data.js written:", data["totals"])
